#!/usr/bin/env python3
"""Generate the printf formatting table and its native g++ reference output."""

import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
CPP = ROOT / "tests" / "c_basics" / "io_printf" / "printf_table.cpp"
EXPECTED = ROOT / "tests" / "c_basics" / "io_printf" / "printf_table.expected"


def main() -> int:
    calls = []

    def add(label, fmt, value):
        calls.append((label, fmt, value))

    # Unsigned conversions must ignore '+' and ' ' while retaining width,
    # precision, zero padding, and alternate-form behavior.
    unsigned = [
        ("u", ["0u", "1u", "42u", "4294967295u"]),
        ("o", ["0u", "1u", "42u", "4294967295u"]),
        ("x", ["0u", "1u", "0x2au", "4294967295u"]),
        ("X", ["0u", "0x2au", "0xbeefu", "4294967295u"]),
    ]
    unsigned_flags = ["", "+", " ", "+0", " 0", "+#", " #"]
    unsigned_shapes = [(0, None), (8, None), (8, 3), (0, 3), (5, 0)]
    for ci, (conv, values) in enumerate(unsigned):
        for fi, flags in enumerate(unsigned_flags):
            for si, (width, precision) in enumerate(unsigned_shapes):
                value = values[(ci + fi + si) % len(values)]
                spec = "%" + flags
                if width:
                    spec += str(width)
                if precision is not None:
                    spec += "." + str(precision)
                spec += conv
                add(f"unsigned_{conv}_{fi}_{si}", spec, value)

    # Alternate form keeps the decimal point and trailing zeros for all float
    # conversions.
    float_specs = [
        ("f", "", 0.0),
        ("f", "+", 1.0),
        ("f", "#", 1.25),
        ("f", "#+", 12345.0),
        ("f", "#0", -2.5),
        ("e", "", 0.0),
        ("e", "#", 1.0),
        ("e", "#+", 1.25),
        ("e", "#0", 0.000123),
        ("E", "#", 12345.0),
        ("E", "#-", -2.5),
        ("g", "", 0.0),
        ("g", "#", 1.0),
        ("g", "#+", 1.25),
        ("g", "#0", 12345.0),
        ("g", "#-", 0.000123),
        ("G", "#", 1.0),
        ("G", "#0", -2.5),
    ]
    shapes = [(0, None), (0, 0), (0, 3), (12, None), (12, 0), (12, 3)]
    for size in (float_specs,):
        for ci, (conv, flags, value) in enumerate(size):
            for si, (width, precision) in enumerate(shapes):
                spec = "%" + flags
                if width:
                    spec += str(width)
                if precision is not None:
                    spec += "." + str(precision)
                spec += conv
                add(f"float_{conv}_{ci}_{si}", spec, repr(value))

    # Zero padding must fall back to spaces for infinities.
    #
    # NaN is deliberately absent: its sign is implementation defined, so g++
    # prints "nan" where clang++ prints "-nan" for the same expression.  The
    # sign-independent properties of a NaN are checked separately below.
    specials = [("inf", "inf"), ("-inf", "-inf")]
    float_modes = ["f", "e", "g"]
    special_flags = ["0", "+0", " 0", "-0"]
    for value_name, value in specials:
        for conv in float_modes:
            for fi, flags in enumerate(special_flags):
                for width in (8, 12):
                    add(
                        f"special_{value_name}_{conv}_{fi}_{width}",
                        "%" + flags + str(width) + conv,
                        value,
                    )

    # Sign-independent properties of a NaN.  Every compiler agrees on these,
    # unlike the printed form of the value itself.
    nan_checks = [
        ("nan_is_not_equal_to_itself", "nan != nan"),
        ("nan_is_not_less_than_zero", "!(nan < 0.0)"),
        ("nan_is_not_greater_than_zero", "!(nan > 0.0)"),
    ]

    # %c honors width and ignores precision and the zero flag.
    for char in ("'A'", "'z'", "'0'"):
        for width in (0, 1, 3, 5):
            for fi, flags in enumerate(("", "-", "0")):
                for precision in (None, 0, 3):
                    spec = "%" + flags
                    if width:
                        spec += str(width)
                    if precision is not None:
                        spec += "." + str(precision)
                    spec += "c"
                    add(f"char_{ord(char.strip(chr(39))[0])}_{width}_{fi}_{precision}", spec, char)

    lines = [
        "// Generated by tools/generate_printf_table.py; expected output comes from g++.",
        "#include <cstdio>",
        "",
        "int main() {",
        "    double inf = 1.0 / 0.0;",
        "    double ninf = -1.0 / 0.0;",
        "    double nan = -(0.0 / 0.0);",
    ]
    for label, fmt, value in calls:
        lines.append(f'    std::printf("{label} [{fmt}]\\n", {value});')
    for label, expr in nan_checks:
        lines.append(f'    std::printf("{label} [%d]\\n", {expr} ? 1 : 0);')
    lines += ["    return 0;", "}", ""]

    CPP.write_text("\n".join(lines), encoding="utf-8")
    with tempfile.TemporaryDirectory() as tmp:
        exe = pathlib.Path(tmp) / "printf_table"
        subprocess.run(
            ["g++", "-std=c++17", "-O0", str(CPP), "-o", str(exe)],
            check=True,
        )
        result = subprocess.run([str(exe)], check=True, stdout=subprocess.PIPE)
    EXPECTED.write_bytes(result.stdout)
    print(f"Wrote {len(calls)} printf cases to {CPP.relative_to(ROOT)}")
    if len(calls) < 200:
        print("error: expected at least 200 cases", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
