use crate::source::{FileId, Span};

#[derive(Debug, Clone, PartialEq)]
pub enum TokenKind {
    // Literals
    IntLiteral(i64, String),
    FloatLiteral(f64, String),
    CharLiteral(char),
    StringLiteral(String),
    BoolLiteral(bool),

    // Identifiers
    Ident(String),

    // Keywords
    KwInt,
    KwLong,
    KwChar,
    KwBool,
    KwFloat,
    KwDouble,
    KwUnsigned,
    KwSigned,
    KwShort,
    KwVoid,
    KwAuto,
    KwConst,
    KwStatic,
    KwIf,
    KwElse,
    KwFor,
    KwWhile,
    KwDo,
    KwSwitch,
    KwCase,
    KwDefault,
    KwBreak,
    KwContinue,
    KwReturn,
    KwThrow,
    KwSizeof,
    KwEnum,
    KwStruct,
    KwClass,
    KwPublic,
    KwPrivate,
    KwProtected,
    KwVirtual,
    KwInline,
    KwExtern,
    KwTemplate,
    KwTypename,
    KwNew,
    KwDelete,
    KwThis,
    KwOperator,
    KwOverride,
    KwNamespace,
    KwUsing,
    KwTypedef,
    KwNullptr,
    KwStaticCast,
    KwConstexpr,
    KwDecltype,
    KwExplicit,
    KwFriend,

    // Operators & Punctuation
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Amp,
    Pipe,
    Caret,
    Tilde,
    Shl,
    Shr,
    AndAnd,
    OrOr,
    Bang,
    EqEq,
    BangEq,
    Lt,
    LtEq,
    Gt,
    GtEq,
    Assign,
    PlusAssign,
    MinusAssign,
    StarAssign,
    SlashAssign,
    PercentAssign,
    AmpAssign,
    PipeAssign,
    CaretAssign,
    ShlAssign,
    ShrAssign,
    PlusPlus,
    MinusMinus,
    Arrow,
    Dot,
    ColonColon,
    Question,
    Colon,
    Comma,
    Semi,
    LParen,
    RParen,
    LBracket,
    RBracket,
    LBrace,
    RBrace,

    Eof,
}

impl TokenKind {
    pub fn diagnostic_name(&self) -> String {
        match self {
            TokenKind::Ident(name) => format!("identifier '{}'", name),
            TokenKind::IntLiteral(..) => "integer literal".into(),
            TokenKind::FloatLiteral(..) => "floating-point literal".into(),
            TokenKind::CharLiteral(_) => "character literal".into(),
            TokenKind::StringLiteral(_) => "string literal".into(),
            TokenKind::BoolLiteral(_) => "boolean literal".into(),
            _ => self
                .diagnostic_keyword_name()
                .or_else(|| self.diagnostic_operator_name())
                .map(str::to_string)
                .unwrap_or_else(|| "token".to_string()),
        }
    }

    fn diagnostic_keyword_name(&self) -> Option<&'static str> {
        match self {
            TokenKind::KwInt => Some("'int'"),
            TokenKind::KwLong => Some("'long'"),
            TokenKind::KwChar => Some("'char'"),
            TokenKind::KwBool => Some("'bool'"),
            TokenKind::KwFloat => Some("'float'"),
            TokenKind::KwDouble => Some("'double'"),
            TokenKind::KwUnsigned => Some("'unsigned'"),
            TokenKind::KwSigned => Some("'signed'"),
            TokenKind::KwShort => Some("'short'"),
            TokenKind::KwVoid => Some("'void'"),
            TokenKind::KwAuto => Some("'auto'"),
            TokenKind::KwConst => Some("'const'"),
            TokenKind::KwStatic => Some("'static'"),
            TokenKind::KwNamespace => Some("'namespace'"),
            TokenKind::KwUsing => Some("'using'"),
            TokenKind::KwTypedef => Some("'typedef'"),
            TokenKind::KwOperator => Some("'operator'"),
            TokenKind::KwStruct => Some("'struct'"),
            TokenKind::KwClass => Some("'class'"),
            TokenKind::KwEnum => Some("'enum'"),
            TokenKind::KwTemplate => Some("'template'"),
            TokenKind::KwTypename => Some("'typename'"),
            TokenKind::KwNew => Some("'new'"),
            TokenKind::KwDelete => Some("'delete'"),
            TokenKind::KwReturn => Some("'return'"),
            TokenKind::KwThrow => Some("'throw'"),
            TokenKind::KwIf => Some("'if'"),
            TokenKind::KwElse => Some("'else'"),
            TokenKind::KwFor => Some("'for'"),
            TokenKind::KwWhile => Some("'while'"),
            TokenKind::KwDo => Some("'do'"),
            TokenKind::KwSwitch => Some("'switch'"),
            TokenKind::KwCase => Some("'case'"),
            TokenKind::KwDefault => Some("'default'"),
            TokenKind::KwBreak => Some("'break'"),
            TokenKind::KwContinue => Some("'continue'"),
            TokenKind::KwThis => Some("'this'"),
            TokenKind::KwVirtual => Some("'virtual'"),
            TokenKind::KwPublic => Some("'public'"),
            TokenKind::KwPrivate => Some("'private'"),
            TokenKind::KwProtected => Some("'protected'"),
            TokenKind::KwInline => Some("'inline'"),
            TokenKind::KwExtern => Some("'extern'"),
            TokenKind::KwOverride => Some("'override'"),
            TokenKind::KwConstexpr => Some("'constexpr'"),
            TokenKind::KwDecltype => Some("'decltype'"),
            TokenKind::KwExplicit => Some("'explicit'"),
            TokenKind::KwFriend => Some("'friend'"),
            _ => None,
        }
    }

    fn diagnostic_operator_name(&self) -> Option<&'static str> {
        match self {
            TokenKind::Plus => Some("'+'"),
            TokenKind::Minus => Some("'-'"),
            TokenKind::Star => Some("'*'"),
            TokenKind::Slash => Some("'/'"),
            TokenKind::Percent => Some("'%'"),
            TokenKind::Amp => Some("'&'"),
            TokenKind::Pipe => Some("'|'"),
            TokenKind::Caret => Some("'^'"),
            TokenKind::Tilde => Some("'~'"),
            TokenKind::Shl => Some("'<<'"),
            TokenKind::Shr => Some("'>>'"),
            TokenKind::AndAnd => Some("'&&'"),
            TokenKind::OrOr => Some("'||'"),
            TokenKind::Bang => Some("'!'"),
            TokenKind::EqEq => Some("'=='"),
            TokenKind::BangEq => Some("'!='"),
            TokenKind::Lt => Some("'<'"),
            TokenKind::LtEq => Some("'<='"),
            TokenKind::Gt => Some("'>'"),
            TokenKind::GtEq => Some("'>='"),
            TokenKind::Assign => Some("'='"),
            TokenKind::PlusAssign => Some("'+='"),
            TokenKind::MinusAssign => Some("'-='"),
            TokenKind::StarAssign => Some("'*='"),
            TokenKind::SlashAssign => Some("'/='"),
            TokenKind::PercentAssign => Some("'%='"),
            TokenKind::AmpAssign => Some("'&='"),
            TokenKind::PipeAssign => Some("'|='"),
            TokenKind::CaretAssign => Some("'^='"),
            TokenKind::ShlAssign => Some("'<<='"),
            TokenKind::ShrAssign => Some("'>>='"),
            TokenKind::PlusPlus => Some("'++'"),
            TokenKind::MinusMinus => Some("'--'"),
            TokenKind::Arrow => Some("'->'"),
            TokenKind::Dot => Some("'.'"),
            TokenKind::ColonColon => Some("'::'"),
            TokenKind::Question => Some("'?'"),
            TokenKind::Colon => Some("':'"),
            TokenKind::Comma => Some("','"),
            TokenKind::Semi => Some("';'"),
            TokenKind::LParen => Some("'('"),
            TokenKind::RParen => Some("')'"),
            TokenKind::LBracket => Some("'['"),
            TokenKind::RBracket => Some("']'"),
            TokenKind::LBrace => Some("'{'"),
            TokenKind::RBrace => Some("'}'"),
            TokenKind::Eof => Some("end of file"),
            _ => None,
        }
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub line: usize,
    pub col: usize,
    pub span: Span,
}

impl Token {
    pub fn new(kind: TokenKind, line: usize, col: usize) -> Self {
        Self {
            kind,
            line,
            col,
            span: Span::point(FileId(0), 0, 0),
        }
    }
}
