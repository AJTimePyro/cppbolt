#include <iostream>
#include <cmath>

int main() {
    std::cout << "abs: " << std::abs(-25) << std::endl;
    std::cout << "sqrt: " << (int)std::sqrt(49.0) << std::endl;
    std::cout << "floor: " << (int)std::floor(3.7) << std::endl;
    std::cout << "ceil: " << (int)std::ceil(3.2) << std::endl;
    return 0;
}
